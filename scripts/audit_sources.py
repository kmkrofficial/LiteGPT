def _rows(job):
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    repo, rev, path = job
    with HfFileSystem().open(f"datasets/{repo}@{rev}/{path}", "rb") as f:
        return pq.ParquetFile(f).metadata.num_rows


def _score(d, i):
    if "int_score" in d:
        return d["int_score"][i]
    m = d.get("metadata", [None] * (i + 1))[i]
    return m.get("int_score") if isinstance(m, dict) else None


def _sample(repo, rev, path, tok, rows=6000):
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    out = {"docs": 0, "tokens": 0, "chars": 0, "bytes": 0, "ge4_docs": 0, "ge4_tokens": 0, "scored": 0}
    with HfFileSystem().open(f"datasets/{repo}@{rev}/{path}", "rb") as f:
        pf = pq.ParquetFile(f)
        names = pf.schema_arrow.names
        cols = [c for c in ("text", "int_score", "metadata") if c in names]
        for b in pf.iter_batches(batch_size=1000, columns=cols):
            d = b.to_pydict()
            encs = tok.encode_batch(d["text"])
            for i, (t, e) in enumerate(zip(d["text"], encs)):
                n = len(e.ids)
                out["docs"] += 1
                out["tokens"] += n
                out["chars"] += len(t)
                out["bytes"] += len(t.encode("utf-8", "replace"))
                s = _score(d, i)
                if s is not None:
                    out["scored"] += 1
                    if s >= 4:
                        out["ge4_docs"] += 1
                        out["ge4_tokens"] += n
            if out["docs"] >= rows:
                break
    return out


def cmd_pretrain(args) -> int:
    from concurrent.futures import ThreadPoolExecutor
    from huggingface_hub import HfApi
    from tokenizers import Tokenizer
    from litegpt.records import create_run
    revs = verified_revisions()
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    rec = create_run("data", "audit-pretrain", config={"sources": PRETRAIN, "revisions": revs, "token_proxy": "gpt2"})
    api, report = HfApi(), {}
    for key, repo, cfg in PRETRAIN:
        rev = revs[repo]
        info = api.dataset_info(repo, revision=rev, files_metadata=True)
        files = sorted((s.rfilename, s.size or 0) for s in info.siblings if s.rfilename.startswith(cfg + "/") and s.rfilename.endswith(".parquet"))
        with ThreadPoolExecutor(16) as ex:
            nrows = list(ex.map(_rows, [(repo, rev, p) for p, _ in files]))
        picks = [files[round(i * (len(files) - 1) / 2)][0] for i in range(3)]
        samp = [_sample(repo, rev, p, tok) for p in picks]
        tot = {k: sum(s[k] for s in samp) for k in samp[0]}
        rows_total = sum(nrows)
        tpd = tot["tokens"] / tot["docs"]
        e = {"repo": repo, "config": cfg, "revision": rev, "n_files": len(files), "parquet_GB": sum(s for _, s in files) / 1e9,
             "rows_total": rows_total, "sample_files": picks, "sample_docs": tot["docs"], "proxy_tokens_per_doc": tpd,
             "chars_per_token": tot["chars"] / tot["tokens"], "bytes_per_token": tot["bytes"] / tot["tokens"],
             "est_total_tokens_B": rows_total * tpd / 1e9,
             "per_file_tokens_per_doc": [s["tokens"] / s["docs"] for s in samp]}
        if tot["scored"]:
            e["share_docs_int_score_ge4"] = tot["ge4_docs"] / tot["scored"]
            e["share_tokens_int_score_ge4"] = tot["ge4_tokens"] / tot["tokens"]
            e["est_ge4_tokens_B"] = e["est_total_tokens_B"] * e["share_tokens_int_score_ge4"]
        report[key] = e
        print(f"{key:18} rev={rev[:8]} files={e['n_files']:4} parquet={e['parquet_GB']:7.1f}GB rows={rows_total / 1e6:8.2f}M "
              f"tok/doc={tpd:7.0f} est_tokens={e['est_total_tokens_B']:7.1f}B bytes/tok={e['bytes_per_token']:.2f} "
              + (f"ge4_tokens={e['est_ge4_tokens_B']:.1f}B ({e['share_tokens_int_score_ge4']:.1%})" if "est_ge4_tokens_B" in e else "no score"))
    rec.write_json("pretrain_audit.json", report)
    print("record:", rec.run_id)
    return 0


SMOLTALK = "HuggingFaceTB/smoltalk"
APACHE_SUBSETS = ["smol-magpie-ultra", "smol-constraints", "smol-rewrite", "smol-summarize"]   # card: "licensed under Apache 2.0"


def cmd_smoltalk(args) -> int:
    import pyarrow.parquet as pq
    from huggingface_hub import HfApi, HfFileSystem
    from tokenizers import Tokenizer
    from litegpt.records import create_run
    rev = verified_revisions()[SMOLTALK]
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    rec = create_run("data", "audit-smoltalk", config={"repo": SMOLTALK, "revision": rev, "allowed": APACHE_SUBSETS, "token_proxy": "gpt2"})
    fs, api = HfFileSystem(), HfApi()
    files = [s.rfilename for s in api.dataset_info(SMOLTALK, revision=rev).siblings]
    counts = collections.Counter()
    for p in sorted(f for f in files if f.startswith("data/all/") and f.endswith(".parquet")):
        with fs.open(f"datasets/{SMOLTALK}@{rev}/{p}", "rb") as f:
            for s in pq.ParquetFile(f).read(columns=["source"]).column("source").to_pylist():
                counts[(p.split("/")[-1].split("-")[0], s)] += 1
    by_source = collections.defaultdict(dict)
    for (split, s), n in counts.items():
        by_source[s][split] = n
    print("rows per source in config 'all':")
    for s, d in sorted(by_source.items(), key=lambda kv: -kv[1].get("train", 0)):
        print(f"  {s:32} {d}  {'ALLOWED (Apache-2.0 per card)' if s in APACHE_SUBSETS else 'excluded (licence ambiguous / defers to upstream)'}")
    report = {"revision": rev, "rows_by_source": {k: v for k, v in by_source.items()}, "allowed": {}}
    for sub in APACHE_SUBSETS:
        tot = {"rows": 0, "tokens": 0, "turns": 0, "sample_rows": 0}
        for p in sorted(f for f in files if f.startswith(f"data/{sub}/") and f.endswith(".parquet") and "/train-" in f):
            with fs.open(f"datasets/{SMOLTALK}@{rev}/{p}", "rb") as f:
                pf = pq.ParquetFile(f)
                tot["rows"] += pf.metadata.num_rows
                if tot["sample_rows"] < 20000:
                    for b in pf.iter_batches(batch_size=2000, columns=["messages"]):
                        msgs = b.to_pydict()["messages"]
                        for m in msgs:
                            tot["turns"] += len(m)
                        encs = tok.encode_batch(["\n".join(x["content"] for x in m) for m in msgs])
                        tot["tokens"] += sum(len(e.ids) + 5 * len(m) for e, m in zip(encs, msgs))
                        tot["sample_rows"] += len(msgs)
                        if tot["sample_rows"] >= 20000:
                            break
        tpr = tot["tokens"] / tot["sample_rows"]
        report["allowed"][sub] = {"rows_train": tot["rows"], "proxy_tokens_per_row": tpr, "turns_per_row": tot["turns"] / tot["sample_rows"],
                                  "est_tokens_M": tot["rows"] * tpr / 1e6}
        print(f"{sub:20} train rows={tot['rows']:8} proxy tok/row={tpr:7.0f} turns/row={tot['turns'] / tot['sample_rows']:.1f} est tokens={tot['rows'] * tpr / 1e6:7.0f}M")
    report["allowed_total_tokens_M"] = sum(v["est_tokens_M"] for v in report["allowed"].values())
    print(f"allowed total ~{report['allowed_total_tokens_M']:.0f}M proxy tokens (decay slice needs ~54M; the rest is for M4 SFT)")
    rec.write_json("smoltalk_audit.json", report)
    print("record:", rec.run_id)
    return 0


PF_TARGET = {"Python": 0.62, "JavaScript": 0.14, "TypeScript": 0.14, "SQL": 0.05, "Shell": 0.05}   # F1
PF_FILES = 210                                                                                      # F4
PF_SAMPLES = 3                                                                                      # kept docs saved per language per file


def _pf_file(job):
    import random
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download
    from tokenizers import Tokenizer
    from litegpt.datafilters import KEEP_LANGUAGES, PERMISSIVE_LICENSES, copyleft_or_secret_after, filter_code
    idx, rev, tmp = job
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    path = hf_hub_download(CODE_REPO, f"data/train-{idx:05d}-of-{N_CODE_FILES:05d}.parquet", repo_type="dataset", revision=rev, local_dir=tmp)
    rng = random.Random(idx)
    stat = {l: collections.Counter() for l in KEEP_LANGUAGES}
    drop_bytes = {l: collections.Counter() for l in KEEP_LANGUAGES}
    samples = {l: [] for l in KEEP_LANGUAGES}
    tokdocs = {l: [] for l in KEEP_LANGUAGES}
    for batch in pq.ParquetFile(path).iter_batches(batch_size=4096, columns=["code", "repo_name", "path", "language", "license", "size"]):
        d = batch.to_pydict()
        for code, repo, p, lang, lc, size in zip(d["code"], d["repo_name"], d["path"], d["language"], d["license"], d["size"]):
            if lang not in stat or not code:
                continue
            c = stat[lang]
            c["docs"] += 1
            c["bytes"] += size
            if lc not in PERMISSIVE_LICENSES:
                continue
            c["perm_docs"] += 1
            c["perm_bytes"] += size
            text, rule = filter_code(code, language=lang, path=p, size=size, counters=c, repo=repo)
            if rule:
                c[f"drop_{rule}"] += 1
                drop_bytes[lang][rule] += size
                continue
            nb = len(text.encode("utf-8", "replace"))
            c["kept_docs"] += 1
            c["kept_bytes"] += nb
            if copyleft_or_secret_after(text):
                c["post_violations"] += 1
            n = c["kept_docs"]
            if len(samples[lang]) < PF_SAMPLES:
                samples[lang].append({"repo": repo, "path": p, "bytes": nb, "head": text[:1500]})
            elif rng.random() < PF_SAMPLES / n:
                samples[lang][rng.randrange(PF_SAMPLES)] = {"repo": repo, "path": p, "bytes": nb, "head": text[:1500]}
            if n % SAMPLE_EVERY == 0:
                tokdocs[lang].append(text)
    tokstats = {}
    for lang, docs in tokdocs.items():
        if docs:
            encs = tok.encode_batch(docs)
            tokstats[lang] = [sum(len(e.ids) for e in encs), sum(len(s.encode("utf-8", "replace")) for s in docs)]
    Path(path).unlink()
    return {"idx": idx, "stat": {k: dict(v) for k, v in stat.items()}, "drop_bytes": {k: dict(v) for k, v in drop_bytes.items()},
            "samples": samples, "tok": tokstats}


def _junk_stats(text: str) -> dict:
    lines = [ln for ln in text.split("\n") if ln.strip()]
    n = max(len(lines), 1)
    return {"lines": len(lines), "mean_line_len": round(sum(map(len, lines)) / n, 1),
            "comment_frac": round(sum(1 for ln in lines if ln.lstrip().startswith(("#", "//", "/*", "*", "--"))) / n, 2),
            "digit_frac": round(sum(map(str.isdigit, text)) / max(len(text), 1), 2),
            "unique_line_frac": round(len(set(lines)) / n, 2)}


def cmd_preflight_code(args) -> int:
    from litegpt.datafilters import KEEP_LANGUAGES, RULES
    from litegpt.records import create_run
    rev = verified_revisions()[CODE_REPO]
    n = args.files
    idxs = sorted({round(i * (N_CODE_FILES - 1) / (n - 1)) for i in range(n)})
    rec = create_run("data", "preflight-code", config={"repo": CODE_REPO, "revision": rev, "file_indices": idxs, "languages": list(KEEP_LANGUAGES),
                     "rules": list(RULES), "targets": PF_TARGET, "code_token_target": CODE_TOKEN_TARGET, "planned_files": PF_FILES, "token_proxy": "gpt2"})
    tmp = tempfile.mkdtemp(prefix="gcc_pf_", dir=str(Path.home()))
    try:
        with ProcessPoolExecutor(max_workers=args.workers) as ex:
            results = list(ex.map(_pf_file, [(i, rev, tmp) for i in idxs]))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    out, nf = {}, len(results)
    for lang in KEEP_LANGUAGES:
        c = collections.Counter()
        tk = [0, 0]
        samples = []
        for r in results:
            c.update(r["stat"][lang])
            samples += r["samples"][lang]
            if lang in r["tok"]:
                tk[0] += r["tok"][lang][0]
                tk[1] += r["tok"][lang][1]
        tpb = tk[0] / tk[1] if tk[1] else None
        kept_tok_file = c["kept_bytes"] / nf * tpb if tpb else None
        supply = kept_tok_file * PF_FILES if kept_tok_file else None
        target = PF_TARGET[lang] * CODE_TOKEN_TARGET
        reach = lambda r: c.get(f"reach_{r}", 0)
        out[lang] = {
            "docs": c["docs"], "permissive_docs": c["perm_docs"], "kept_docs": c["kept_docs"],
            "kept_over_permissive_docs": c["kept_docs"] / max(c["perm_docs"], 1),
            "tokens_per_byte": tpb, "kept_tokens_per_file_M": kept_tok_file / 1e6 if kept_tok_file else None,
            "supply_over_planned_files_M": supply / 1e6 if supply else None, "target_M": target / 1e6,
            "margin_x": supply / target if supply else None,
            "drop_docs": {r: c.get(f"drop_{r}", 0) for r in RULES}, "reach_docs": {r: reach(r) for r in RULES},
            "drop_rate_at_stage": {r: c.get(f"drop_{r}", 0) / reach(r) for r in RULES if reach(r)},
            "secret_hits_before_rule": {k[7:]: v for k, v in c.items() if k.startswith("secret_")},
            "copyleft_header_rate_before_rule": c.get("drop_copyleft", 0) / max(reach("copyleft"), 1),
            "email_redacted_docs": c.get("email_redacted_docs", 0), "post_violations": c.get("post_violations", 0),
            "samples": [dict(s, **_junk_stats(s["head"])) for s in samples],
        }
    # C4 rule (pre-registered): SQL / Shell below 1.10x target over the planned files -> 0.04 each, Python +0.01 each
    c4 = {l: (out[l]["margin_x"] is not None and out[l]["margin_x"] >= 1.10) for l in ("SQL", "Shell")}
    final_w = dict(PF_TARGET)
    for l, ok in c4.items():
        if not ok:
            final_w[l] = 0.04
            final_w["Python"] = round(final_w["Python"] + 0.01, 4)
    print(f"files audited: {nf} of {N_CODE_FILES}; planned input files: {PF_FILES}")
    print(f"{'language':11} {'kept/perm':>9} {'tok/file M':>10} {'supply M':>9} {'target M':>9} {'margin':>7} {'copyleft%':>9} {'post-viol':>9}")
    for lang, o in out.items():
        print(f"{lang:11} {o['kept_over_permissive_docs']:9.1%} {(o['kept_tokens_per_file_M'] or 0):10.2f} "
              f"{o['supply_over_planned_files_M'] or 0:9.0f} {o['target_M']:9.0f} {(o['margin_x'] or 0):7.2f} "
              f"{o['copyleft_header_rate_before_rule']:9.2%} {o['post_violations']:9}")
        print("   drops by rule (docs):", {k: v for k, v in o["drop_docs"].items() if v}, "| secrets before rule:", o["secret_hits_before_rule"],
              "| emails redacted docs:", o["email_redacted_docs"])
    print("C4:", c4, "-> final weights", final_w)
    rec.write_json("preflight_code.json", {"revision": rev, "files": idxs, "languages": out, "c4": c4, "final_weights": final_w})
    print("record:", rec.run_id)
    return 0


