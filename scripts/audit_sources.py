"""Source audit (M1 step 1b): exact revisions, licences, available tokens and language distribution, from the data itself.

Subcommands: code (github-code-clean across 12 evenly spaced files), pretrain (row counts and token estimates for the web,
synthetic and math sources), smoltalk (Apache-2.0-labelled subsets). Token counts here use the GPT-2 tokenizer as a PROXY
(the LiteGPT 32k tokenizer does not exist yet); final counts come from the frozen tokenizer in step 5. Everything is read-only
and written to a `data` run record.
"""
from __future__ import annotations

import argparse
import ast
import collections
import hashlib
import json
import re
import shutil
import sys
import tempfile
import warnings
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

CODE_REPO = "codeparrot/github-code-clean"
N_CODE_FILES = 880
PERMISSIVE = {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "cc0-1.0", "unlicense"}
MAX_BYTES, MAX_LINE, MIN_ALNUM = 100_000, 1000, 0.25          # registered filters (EXP-M1-CODE)
AUTOGEN = re.compile(r"auto[- ]?generated|autogenerated|generated by|do not edit|this file was generated|automatically generated", re.I)
SAMPLE_EVERY = 30
# Proposed within-code language weights (a proposal; the audit reports availability against it).
PROPOSED = {"Python": 0.35, "JavaScript": 0.10, "TypeScript": 0.06, "Java": 0.10, "C": 0.08, "C++": 0.08, "GO": 0.05,
            "Rust": 0.04, "SQL": 0.02, "Shell": 0.03, "C#": 0.04, "PHP": 0.03, "Ruby": 0.02}
CODE_TOKEN_TARGET = 1.98e9    # (1.75B stable + 0.173B decay) x 1.03 margin, with Wikipedia's share redistributed


def verified_revisions() -> dict:
    runs = sorted((ROOT / "runs").glob("*data-verify-sources*/verify.json"))
    out = {}
    for e in json.loads(runs[-1].read_text(encoding="utf-8")):
        out.setdefault(e["repo"], e["sha"])
    return out


def _process_file(job):
    idx, rev, tmp = job
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download
    from tokenizers import Tokenizer
    warnings.simplefilter("ignore")
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    path = hf_hub_download(CODE_REPO, f"data/train-{idx:05d}-of-{N_CODE_FILES:05d}.parquet", repo_type="dataset",
                           revision=rev, local_dir=tmp)
    langs = collections.defaultdict(collections.Counter)
    lic = collections.defaultdict(collections.Counter)
    samples = collections.defaultdict(list)
    py_parse = [0, 0]
    hashes = []
    pf = pq.ParquetFile(path)
    for batch in pf.iter_batches(batch_size=4096, columns=["code", "language", "license", "size"]):
        d = batch.to_pydict()
        for code, lang, lc, size in zip(d["code"], d["language"], d["license"], d["size"]):
            if not code:
                continue
            c = langs[lang]
            c["docs"] += 1
            c["bytes"] += size
            lic[lang][lc] += size
            if lc not in PERMISSIVE:
                continue
            c["perm_docs"] += 1
            c["perm_bytes"] += size
            if size > MAX_BYTES:
                c["drop_size_bytes"] += size
                continue
            lines = code.split("\n")
            if max(map(len, lines)) > MAX_LINE:
                c["drop_longline_bytes"] += size
                continue
            if sum(map(str.isalnum, code)) < MIN_ALNUM * len(code):
                c["drop_alnum_bytes"] += size
                continue
            if AUTOGEN.search("\n".join(lines[:6])):
                c["drop_autogen_bytes"] += size
                continue
            c["kept_docs"] += 1
            c["kept_bytes"] += size
            hashes.append(int.from_bytes(hashlib.md5(code.encode("utf-8", "replace")).digest()[:8], "little"))
            if c["kept_docs"] % SAMPLE_EVERY == 0:
                samples[lang].append(code)
            if lang == "Python" and c["kept_docs"] % 20 == 0 and py_parse[1] < 400:
                py_parse[1] += 1
                try:
                    ast.parse(code)
                    py_parse[0] += 1
                except Exception:
                    pass
    tokstats = {}
    for lang, docs in samples.items():
        encs = tok.encode_batch(docs)
        tokstats[lang] = [sum(len(e.ids) for e in encs), sum(len(s.encode("utf-8", "replace")) for s in docs)]
    Path(path).unlink()
    return {"idx": idx, "langs": {k: dict(v) for k, v in langs.items()}, "lic": {k: dict(v) for k, v in lic.items()},
            "tok": tokstats, "py_parse": py_parse, "hashes": hashes}


def cmd_code(args) -> int:
    from litegpt.records import create_run
    rev = verified_revisions()[CODE_REPO]
    n = args.files
    idxs = sorted({round(i * (N_CODE_FILES - 1) / (n - 1)) for i in range(n)})
    rec = create_run("data", "audit-code", config={"repo": CODE_REPO, "revision": rev, "file_indices": idxs,
                     "permissive": sorted(PERMISSIVE), "filters": {"max_bytes": MAX_BYTES, "max_line": MAX_LINE, "min_alnum": MIN_ALNUM},
                     "token_proxy": "gpt2", "proposed_weights": PROPOSED, "code_token_target": CODE_TOKEN_TARGET})
    tmp = tempfile.mkdtemp(prefix="gcc_audit_", dir=str(Path.home()))
    try:
        with ProcessPoolExecutor(max_workers=args.workers) as ex:
            results = list(ex.map(_process_file, [(i, rev, tmp) for i in idxs]))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    agg = collections.defaultdict(collections.Counter)
    per_file = collections.defaultdict(list)
    tok = collections.defaultdict(lambda: [0, 0])
    lic_all, lic_py = collections.Counter(), collections.Counter()
    for r in results:
        for lang, c in r["langs"].items():
            agg[lang].update(c)
            per_file[lang].append(c.get("kept_bytes", 0))
        for lang, m in r["lic"].items():
            for k, v in m.items():
                lic_all[k] += v
                if lang == "Python":
                    lic_py[k] += v
        for lang, (t, b) in r["tok"].items():
            tok[lang][0] += t
            tok[lang][1] += b
    allh = [h for r in results for h in r["hashes"]]
    dup_rate = 1 - len(set(allh)) / max(len(allh), 1)
    py_ok = sum(r["py_parse"][0] for r in results), sum(r["py_parse"][1] for r in results)
    total_bytes = sum(c["bytes"] for c in agg.values())
    perm_bytes = sum(c["perm_bytes"] for c in agg.values())
    rows = []
    for lang, c in agg.items():
        tpb = tok[lang][0] / tok[lang][1] if tok[lang][1] else None
        kb_file = c["kept_bytes"] / len(results)
        pf = per_file[lang]
        mean = sum(pf) / len(pf)
        cv = (sum((x - mean) ** 2 for x in pf) / len(pf)) ** 0.5 / mean if mean else None
        rows.append({"language": lang, "share_of_all_bytes": c["bytes"] / total_bytes, "permissive_bytes_share": c["perm_bytes"] / max(c["bytes"], 1),
                     "kept_over_permissive": c["kept_bytes"] / max(c["perm_bytes"], 1), "kept_MB_per_file": kb_file / 1e6,
                     "tokens_per_byte": tpb, "kept_tokens_per_file_M": (kb_file * tpb / 1e6) if tpb else None,
                     "kept_tokens_total_B": (kb_file * tpb * N_CODE_FILES / 1e9) if tpb else None, "cv_across_files": cv,
                     "docs_kept_per_file": c["kept_docs"] / len(results),
                     "drops_MB_per_file": {k[5:-6]: v / len(results) / 1e6 for k, v in c.items() if k.startswith("drop_")}})
    rows.sort(key=lambda r: -(r["kept_tokens_total_B"] or 0))
    print(f"files audited: {len(results)} of {N_CODE_FILES}; permissive share of bytes: {perm_bytes / total_bytes:.1%}; "
          f"cross-file duplicate rate among kept docs: {dup_rate:.3%}; python ast.parse ok: {py_ok[0]}/{py_ok[1]}")
    print(f"{'language':12} {'allB%':>6} {'perm%':>6} {'kept/perm':>9} {'MB/file':>8} {'tok/B':>6} {'Mtok/file':>9} {'total Btok':>10} {'CV':>5}")
    for r in rows[:22]:
        print(f"{r['language']:12} {r['share_of_all_bytes']:6.1%} {r['permissive_bytes_share']:6.1%} {r['kept_over_permissive']:9.1%} "
              f"{r['kept_MB_per_file']:8.1f} {(r['tokens_per_byte'] or 0):6.3f} {(r['kept_tokens_per_file_M'] or 0):9.2f} "
              f"{(r['kept_tokens_total_B'] or 0):10.2f} {(r['cv_across_files'] or 0):5.2f}")
    print("licence mix, all docs (bytes):", [(k, f"{v / sum(lic_all.values()):.1%}") for k, v in lic_all.most_common(10)])
    print("licence mix, Python (bytes):", [(k, f"{v / sum(lic_py.values()):.1%}") for k, v in lic_py.most_common(8)])
    by = {r["language"]: r for r in rows}
    need = {}
    for lang, w in PROPOSED.items():
        r = by.get(lang)
        tpf = r["kept_tokens_per_file_M"] if r else None
        need[lang] = {"weight": w, "target_tokens_M": w * CODE_TOKEN_TARGET / 1e6,
                      "files_needed": (w * CODE_TOKEN_TARGET / (tpf * 1e6)) if tpf else None,
                      "available_total_B": r["kept_tokens_total_B"] if r else None}
    binding = max(need, key=lambda k: need[k]["files_needed"] or 0)
    print("proposed weights -> files needed (of 880; ~0.356 GB each):")
    for k, v in need.items():
        fn = v["files_needed"]
        print(f"  {k:11} w={v['weight']:.2f} target={v['target_tokens_M']:7.0f}M files={fn if fn is None else round(fn, 1)} available={v['available_total_B']}B")
    print(f"binding language: {binding}; files needed {need[binding]['files_needed']:.0f} (~{need[binding]['files_needed'] * 0.356:.0f} GB download)")
    rec.write_json("code_audit.json", {"revision": rev, "files": idxs, "rows": rows, "need": need, "binding": binding,
                                       "licence_all": dict(lic_all), "licence_python": dict(lic_py), "dup_rate_kept": dup_rate,
                                       "python_parse_ok": py_ok, "permissive_share_of_bytes": perm_bytes / total_bytes})
    print("record:", rec.run_id)
    return 0


PRETRAIN = [  # (key, repo, config)
    ("fineweb_edu_dedup", "HuggingFaceTB/smollm-corpus", "fineweb-edu-dedup"),
    ("cosmopedia_v2", "HuggingFaceTB/smollm-corpus", "cosmopedia-v2"),
    ("finemath_3plus", "HuggingFaceTB/finemath", "finemath-3plus"),
    ("finemath_4plus", "HuggingFaceTB/finemath", "finemath-4plus"),
]


def _rows(job):
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    repo, rev, path = job
    with HfFileSystem().open(f"datasets/{repo}@{rev}/{path}", "rb") as f:
        return pq.ParquetFile(f).metadata.num_rows


def _score(d, i):
    if "int_score" in d:
        return d["int_score"][i]
    m = d.get("metadata", [None] * (i + 1))[i]
    return m.get("int_score") if isinstance(m, dict) else None


def _sample(repo, rev, path, tok, rows=6000):
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    out = {"docs": 0, "tokens": 0, "chars": 0, "bytes": 0, "ge4_docs": 0, "ge4_tokens": 0, "scored": 0}
    with HfFileSystem().open(f"datasets/{repo}@{rev}/{path}", "rb") as f:
        pf = pq.ParquetFile(f)
        names = pf.schema_arrow.names
        cols = [c for c in ("text", "int_score", "metadata") if c in names]
        for b in pf.iter_batches(batch_size=1000, columns=cols):
            d = b.to_pydict()
            encs = tok.encode_batch(d["text"])
            for i, (t, e) in enumerate(zip(d["text"], encs)):
                n = len(e.ids)
                out["docs"] += 1
                out["tokens"] += n
                out["chars"] += len(t)
                out["bytes"] += len(t.encode("utf-8", "replace"))
                s = _score(d, i)
                if s is not None:
                    out["scored"] += 1
                    if s >= 4:
                        out["ge4_docs"] += 1
                        out["ge4_tokens"] += n
            if out["docs"] >= rows:
                break
    return out


def cmd_pretrain(args) -> int:
    from concurrent.futures import ThreadPoolExecutor
    from huggingface_hub import HfApi
    from tokenizers import Tokenizer
    from litegpt.records import create_run
    revs = verified_revisions()
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    rec = create_run("data", "audit-pretrain", config={"sources": PRETRAIN, "revisions": revs, "token_proxy": "gpt2"})
    api, report = HfApi(), {}
    for key, repo, cfg in PRETRAIN:
        rev = revs[repo]
        info = api.dataset_info(repo, revision=rev, files_metadata=True)
        files = sorted((s.rfilename, s.size or 0) for s in info.siblings if s.rfilename.startswith(cfg + "/") and s.rfilename.endswith(".parquet"))
        with ThreadPoolExecutor(16) as ex:
            nrows = list(ex.map(_rows, [(repo, rev, p) for p, _ in files]))
        picks = [files[round(i * (len(files) - 1) / 2)][0] for i in range(3)]
        samp = [_sample(repo, rev, p, tok) for p in picks]
        tot = {k: sum(s[k] for s in samp) for k in samp[0]}
        rows_total = sum(nrows)
        tpd = tot["tokens"] / tot["docs"]
        e = {"repo": repo, "config": cfg, "revision": rev, "n_files": len(files), "parquet_GB": sum(s for _, s in files) / 1e9,
             "rows_total": rows_total, "sample_files": picks, "sample_docs": tot["docs"], "proxy_tokens_per_doc": tpd,
             "chars_per_token": tot["chars"] / tot["tokens"], "bytes_per_token": tot["bytes"] / tot["tokens"],
             "est_total_tokens_B": rows_total * tpd / 1e9,
             "per_file_tokens_per_doc": [s["tokens"] / s["docs"] for s in samp]}
        if tot["scored"]:
            e["share_docs_int_score_ge4"] = tot["ge4_docs"] / tot["scored"]
            e["share_tokens_int_score_ge4"] = tot["ge4_tokens"] / tot["tokens"]
            e["est_ge4_tokens_B"] = e["est_total_tokens_B"] * e["share_tokens_int_score_ge4"]
        report[key] = e
        print(f"{key:18} rev={rev[:8]} files={e['n_files']:4} parquet={e['parquet_GB']:7.1f}GB rows={rows_total / 1e6:8.2f}M "
              f"tok/doc={tpd:7.0f} est_tokens={e['est_total_tokens_B']:7.1f}B bytes/tok={e['bytes_per_token']:.2f} "
              + (f"ge4_tokens={e['est_ge4_tokens_B']:.1f}B ({e['share_tokens_int_score_ge4']:.1%})" if "est_ge4_tokens_B" in e else "no score"))
    rec.write_json("pretrain_audit.json", report)
    print("record:", rec.run_id)
    return 0


SMOLTALK = "HuggingFaceTB/smoltalk"
APACHE_SUBSETS = ["smol-magpie-ultra", "smol-constraints", "smol-rewrite", "smol-summarize"]   # card: "licensed under Apache 2.0"


def cmd_smoltalk(args) -> int:
    import pyarrow.parquet as pq
    from huggingface_hub import HfApi, HfFileSystem
    from tokenizers import Tokenizer
    from litegpt.records import create_run
    rev = verified_revisions()[SMOLTALK]
    tok = Tokenizer.from_pretrained("openai-community/gpt2")
    rec = create_run("data", "audit-smoltalk", config={"repo": SMOLTALK, "revision": rev, "allowed": APACHE_SUBSETS, "token_proxy": "gpt2"})
    fs, api = HfFileSystem(), HfApi()
    files = [s.rfilename for s in api.dataset_info(SMOLTALK, revision=rev).siblings]
    counts = collections.Counter()
    for p in sorted(f for f in files if f.startswith("data/all/") and f.endswith(".parquet")):
        with fs.open(f"datasets/{SMOLTALK}@{rev}/{p}", "rb") as f:
            for s in pq.ParquetFile(f).read(columns=["source"]).column("source").to_pylist():
                counts[(p.split("/")[-1].split("-")[0], s)] += 1
    by_source = collections.defaultdict(dict)
    for (split, s), n in counts.items():
        by_source[s][split] = n
    print("rows per source in config 'all':")
    for s, d in sorted(by_source.items(), key=lambda kv: -kv[1].get("train", 0)):
        print(f"  {s:32} {d}  {'ALLOWED (Apache-2.0 per card)' if s in APACHE_SUBSETS else 'excluded (licence ambiguous / defers to upstream)'}")
    report = {"revision": rev, "rows_by_source": {k: v for k, v in by_source.items()}, "allowed": {}}
    for sub in APACHE_SUBSETS:
        tot = {"rows": 0, "tokens": 0, "turns": 0, "sample_rows": 0}
        for p in sorted(f for f in files if f.startswith(f"data/{sub}/") and f.endswith(".parquet") and "/train-" in f):
            with fs.open(f"datasets/{SMOLTALK}@{rev}/{p}", "rb") as f:
                pf = pq.ParquetFile(f)
                tot["rows"] += pf.metadata.num_rows
                if tot["sample_rows"] < 20000:
                    for b in pf.iter_batches(batch_size=2000, columns=["messages"]):
                        msgs = b.to_pydict()["messages"]
                        for m in msgs:
                            tot["turns"] += len(m)
                        encs = tok.encode_batch(["\n".join(x["content"] for x in m) for m in msgs])
                        tot["tokens"] += sum(len(e.ids) + 5 * len(m) for e, m in zip(encs, msgs))
                        tot["sample_rows"] += len(msgs)
                        if tot["sample_rows"] >= 20000:
                            break
        tpr = tot["tokens"] / tot["sample_rows"]
        report["allowed"][sub] = {"rows_train": tot["rows"], "proxy_tokens_per_row": tpr, "turns_per_row": tot["turns"] / tot["sample_rows"],
                                  "est_tokens_M": tot["rows"] * tpr / 1e6}
        print(f"{sub:20} train rows={tot['rows']:8} proxy tok/row={tpr:7.0f} turns/row={tot['turns'] / tot['sample_rows']:.1f} est tokens={tot['rows'] * tpr / 1e6:7.0f}M")
    report["allowed_total_tokens_M"] = sum(v["est_tokens_M"] for v in report["allowed"].values())
    print(f"allowed total ~{report['allowed_total_tokens_M']:.0f}M proxy tokens (decay slice needs ~54M; the rest is for M4 SFT)")
    rec.write_json("smoltalk_audit.json", report)
    print("record:", rec.run_id)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("code")
    c.add_argument("--files", type=int, default=12)
    c.add_argument("--workers", type=int, default=4)
    sub.add_parser("pretrain")
    sub.add_parser("smoltalk")
    args = ap.parse_args()
    return {"code": cmd_code, "pretrain": cmd_pretrain, "smoltalk": cmd_smoltalk}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
