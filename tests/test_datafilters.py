import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from litegpt.datafilters import MAX_BYTES, filter_code  # noqa: E402


def kept(text, **kw):
    return filter_code(text, **kw)[1]


def test_clean_python_is_kept():
    out, rule = filter_code("def f(x):\n    return x + 1\n", language="Python")
    assert rule is None and out.startswith("def f")


def test_python2_syntax_is_dropped():
    assert kept("print 'hello'\n", language="Python") == "pyparse"
    assert kept("print 'hello'\n", language="Shell") is None      # the parse rule is Python-only


def test_size_longline_alnum_autogen():
    assert kept("x" * (MAX_BYTES + 1), language="Shell") == "size"
    assert kept("a = '" + "x" * 1200 + "'\n", language="Python") == "longline"
    assert kept("-" * 400 + "\n", language="Shell") == "alnum"
    assert kept("# Auto-generated by protoc\nx = 1\n", language="Python") == "autogen"


def test_vendored_and_minified_paths():
    assert kept("x = 1;\n", language="JavaScript", path="web/node_modules/a/b.js") == "path"
    assert kept("x = 1;\n", language="JavaScript", path="static/app.min.js") == "path"
    assert kept("export {}\n", language="TypeScript", path="src/types.d.ts") == "path"
    assert kept("export const a = 1\n", language="TypeScript", path="src/types.ts") is None
    assert kept("x = 1;\n", language="JavaScript", path=None) is None


def test_sql_dump_vs_query():
    dump = "INSERT INTO t VALUES (1, 'a');\n" * 5 + "(2),\n(3),\n"
    assert kept(dump, language="SQL") == "sqldump"
    assert kept("SELECT a, b\nFROM t\nWHERE a > 1\nORDER BY b;\n", language="SQL") is None


def test_copyleft_header_only_in_first_lines():
    assert kept("# This program is free software under the GNU General Public License v3\nx = 1\n", language="Python") == "copyleft"
    assert kept("x = 1\n" * 100 + "# GPL mention far below\n", language="Python") is None


def test_secrets_dropped_and_emails_redacted():
    assert kept("key = '-----BEGIN RSA PRIVATE KEY-----'\n", language="Python") == "secret"
    assert kept("aws = 'AKIA" + "ABCDEFGHIJKLMNOP" + "'\n", language="Python") == "secret"
    out, rule = filter_code("# contact: someone@example.com\nx = 1\n", language="Python")
    assert rule is None and "<EMAIL>" in out and "someone@example.com" not in out


def test_counters_record_reach_and_hits():
    c = {}
    filter_code("x = 1\n", language="Python", counters=c)
    assert c["reach_size"] == 1 and c["reach_secret"] == 1 and c["reach_pyparse"] == 1
    filter_code("aws = 'AKIA" + "ABCDEFGHIJKLMNOP" + "'\n", language="Python", counters=c)
    assert c["secret_aws_access_key"] == 1


def test_export_dump_and_library_mirror_rules():
    assert kept("/*\nNavicat MySQL Data Transfer\n*/\nCREATE TABLE a (id int);\n", language="SQL") == "exportdump"
    assert kept("SELECT 1;\n", language="SQL") is None
    assert kept("var a = 1;\n", language="JavaScript", repo="cdnjs/cdnjs", path="x/y.js") == "mirror"
    assert kept("var a = 1;\n", language="JavaScript", repo="me/app", path="ajax/libs/foo/1.0/foo.js") == "mirror"
    assert kept("var a = 1;\n", language="JavaScript", repo="me/app", path="lib/output/model.js") is None
