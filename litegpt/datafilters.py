"""Document filters for the code source (registered in docs/spec/registry.yaml, EXP-M1-PREFLIGHT).

One function, `filter_code`, applies the rules in a fixed order and returns the first rule that rejects a document, or the
(email-redacted) text if it is kept. The same module is used by the audit scripts and by `scripts/prepare_data.py`, so the
numbers measured in pre-flight are the numbers the preparation run produces. Standard library only.
"""
from __future__ import annotations

import ast
import re
import warnings

PERMISSIVE_LICENSES = frozenset({"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "cc0-1.0", "unlicense"})
KEEP_LANGUAGES = ("Python", "JavaScript", "TypeScript", "SQL", "Shell")      # names as in github-code-clean
MAX_BYTES, MAX_LINE, MIN_ALNUM = 100_000, 1000, 0.25
HEADER_LINES = 60

AUTOGEN = re.compile(r"auto[- ]?generated|autogenerated|generated by|do not edit|this file was generated|automatically generated", re.I)
COPYLEFT = re.compile(r"GNU\s+(?:Affero\s+|Lesser\s+|Library\s+)?General\s+Public\s+License|\b(?:A|L)?GPL(?:v?[23])?\b", re.I)
VENDOR_DIRS = frozenset({"node_modules", "vendor", "dist", "build", "third_party", "bower_components"})
VENDOR_SUFFIXES = (".min.js", ".bundle.js", ".min.css")
SQL_DUMP_LINE = re.compile(r"^\s*(?:insert\s+into\b|values\b|\()", re.I)
EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
SECRETS = {
    "private_key": re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP |ENCRYPTED )?PRIVATE KEY"),
    "aws_access_key": re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    "github_token": re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36}\b|\bgithub_pat_[A-Za-z0-9_]{22,}\b"),
    "slack_token": re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}\b"),
    "google_api_key": re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b"),
    "stripe_live_key": re.compile(r"\bsk_live_[0-9a-zA-Z]{24,}\b"),
}
EXPORT_DUMP = re.compile(r"navicat|phpmyadmin sql dump|mysqldump|dumping data for table", re.I)
MIRROR_REPO = re.compile(r"cdnjs|jsdelivr|unpkg", re.I)
RULES = ("size", "longline", "alnum", "autogen", "path", "mirror", "pyparse", "sqldump", "exportdump", "copyleft", "secret")


def secret_classes(text: str) -> list[str]:
    return [name for name, rx in SECRETS.items() if rx.search(text)]


def has_copyleft_header(text: str) -> bool:
    return bool(COPYLEFT.search("\n".join(text.split("\n", HEADER_LINES)[:HEADER_LINES])))


def copyleft_or_secret_after(text: str) -> bool:
    """Post-hoc rescan of an already kept document (must be False for every kept document)."""
    return has_copyleft_header(text) or bool(secret_classes(text))


def vendored_path(path: str | None, language: str) -> bool:
    if not path:
        return False
    p = path.replace("\\", "/").lower()
    if any(part in VENDOR_DIRS for part in p.split("/")[:-1]) or p.endswith(VENDOR_SUFFIXES):
        return True
    return language == "TypeScript" and p.endswith(".d.ts")


def sql_dump_fraction(text: str) -> float:
    lines = [ln for ln in text.split("\n") if ln.strip()]
    return sum(1 for ln in lines if SQL_DUMP_LINE.match(ln)) / len(lines) if lines else 0.0


def python3_parses(text: str) -> bool:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:
            ast.parse(text)
            return True
        except (SyntaxError, ValueError, RecursionError, MemoryError):
            return False


def filter_code(text: str, *, language: str, path: str | None = None, size: int | None = None, rules: tuple = RULES,
                counters: dict | None = None, repo: str | None = None) -> tuple[str | None, str | None]:
    """Return (kept_text, None) or (None, rule). `counters`, if given, gets `reach_<rule>` for every rule evaluated and
    `secret_<class>` / `copyleft` / `email` hit counts among documents that reach those rules."""
    c = counters if counters is not None else {}

    def reach(rule: str) -> None:
        c[f"reach_{rule}"] = c.get(f"reach_{rule}", 0) + 1

    nbytes = size if size is not None else len(text.encode("utf-8", "replace"))
    if "size" in rules:
        reach("size")
        if nbytes > MAX_BYTES:
            return None, "size"
    lines = text.split("\n")
    if "longline" in rules:
        reach("longline")
        if max(map(len, lines)) > MAX_LINE:
            return None, "longline"
    if "alnum" in rules:
        reach("alnum")
        if sum(map(str.isalnum, text)) < MIN_ALNUM * len(text):
            return None, "alnum"
    if "autogen" in rules:
        reach("autogen")
        if AUTOGEN.search("\n".join(lines[:6])):
            return None, "autogen"
    if "path" in rules:
        reach("path")
        if vendored_path(path, language):
            return None, "path"
    if "mirror" in rules and language in ("JavaScript", "TypeScript"):
        reach("mirror")
        if (repo and MIRROR_REPO.search(repo)) or (path and "ajax/libs/" in path.replace("\\", "/").lower()):
            return None, "mirror"
    if "pyparse" in rules and language == "Python":
        reach("pyparse")
        if not python3_parses(text):
            return None, "pyparse"
    if "sqldump" in rules and language == "SQL":
        reach("sqldump")
        if sql_dump_fraction(text) > 0.5:
            return None, "sqldump"
    if "exportdump" in rules and language == "SQL":
        reach("exportdump")
        if EXPORT_DUMP.search(chr(10).join(lines[:20])):
            return None, "exportdump"
    if "copyleft" in rules:
        reach("copyleft")
        if has_copyleft_header(text):
            return None, "copyleft"
    if "secret" in rules:
        reach("secret")
        hits = secret_classes(text)
        for h in hits:
            c[f"secret_{h}"] = c.get(f"secret_{h}", 0) + 1
        if hits:
            return None, "secret"
    if EMAIL.search(text):
        c["email_redacted_docs"] = c.get("email_redacted_docs", 0) + 1
        text = EMAIL.sub("<EMAIL>", text)
    return text, None
